// Builds src/locales/<code>.json from the translation tables in src/locales/source/*.tsv.
// Each table has a header row (en, es, fr, de, …) and one row per English text; "\n" means a new line.
//   node scripts/i18n-build.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/locales/source');
const out = {};
const conflicts = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith('.tsv')).sort()) {
  const [head, ...rows] = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').split('\n').filter((l) => l.length);
  const langs = head.split('\t');
  if (langs[0] !== 'en') throw new Error(`${file}: the first column must be "en"`);
  rows.forEach((row, i) => {
    const cells = row.split('\t').map((c) => c.replace(/\\n/g, '\n'));
    if (cells.length !== langs.length) throw new Error(`${file}:${i + 2}: expected ${langs.length} columns, found ${cells.length}`);
    const en = cells[0];
    langs.slice(1).forEach((lang, k) => {
      out[lang] ??= {};
      const value = cells[k + 1];
      if (!value) return;
      if (out[lang][en] !== undefined && out[lang][en] !== value) conflicts.push(`${lang}: “${en}” → “${out[lang][en]}” / “${value}” (${file})`);
      else out[lang][en] = value;
    });
  });
}
for (const [lang, dict] of Object.entries(out)) {
  const sorted = Object.fromEntries(Object.entries(dict).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(join(root, 'src/locales', `${lang}.json`), `${JSON.stringify({ _comment: 'Generated by scripts/i18n-build.mjs from src/locales/source/*.tsv — edit those.', ...sorted }, null, 1)}\n`);
  console.log(`${lang}: ${Object.keys(dict).length} entries`);
}
if (conflicts.length) { console.error(`Different translations for the same text (the first was kept):\n${conflicts.join('\n')}`); process.exitCode = 1; }
